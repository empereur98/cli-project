#!/bin/bash

show_help() {
  echo -e "\033[1;37mNX - Autonomous Nuxt Module & Project Scaffolder\033[0m"
  echo -e "\033[0;36mUsage:\033[0m"
  echo -e "  ./nx <command> [options] [args]"
  echo ""
  echo -e "\033[0;36mCommands:\033[0m"
  echo -e "  \033[1;32mcreate <project_name>\033[0m        Scaffold new Nuxt project with Tailwind & embedded ./nx"
  echo -e "  \033[1;32m-m, --module <name>\033[0m          Scaffold local feature module in ./modules/ (must run in project)"
  echo -e "  \033[1;32m-d, --delete <name>\033[0m          Remove module or model from main project"
  echo -e "  \033[1;32m--init\033[0m                       Initialize global 'nx' CLI in system/user PATH"
  echo -e "  \033[1;32m-i, --import [url|name]\033[0m      Import module(s) from nx.config.json or GitHub URL"
  echo -e "  \033[1;32m-u, --update [name]\033[0m          Pull latest Git changes for a module or all modules"
  echo -e "  \033[1;32m-l, --list\033[0m                   List all installed modules with version, repo, and role"
  echo -e "  \033[1;32mman, --man\033[0m                   Open the manual documentation page (man nx)"
  echo -e "  \033[1;32m-h, --help\033[0m                   Display this help message and exit"
  echo ""
  echo -e "\033[0;36mExamples:\033[0m"
  echo -e "  ./nx --init"
  echo -e "  ./nx create trading-frontend"
  echo -e "  ./nx -m trading-auth"
  echo -e "  ./nx -m trading-auth -d"
  echo -e "  ./nx -d trading-auth"
  echo -e "  ./nx -i https://github.com/my-org/trading-auth.git"
  echo -e "  ./nx -u trading-auth"
  echo -e "  ./nx -l"
  echo -e "  ./nx man"
  echo ""
}
